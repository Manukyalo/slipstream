-- 0. Prerequisites
CREATE EXTENSION IF NOT EXISTS pg_trgm;

-- 1. Extend vehicle_makes
ALTER TABLE public.vehicle_makes
  ADD COLUMN IF NOT EXISTS slug       TEXT,
  ADD COLUMN IF NOT EXISTS status     TEXT NOT NULL DEFAULT 'approved'
                                           CHECK (status IN ('approved','pending','rejected')),
  ADD COLUMN IF NOT EXISTS created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL;

UPDATE public.vehicle_makes
  SET slug = lower(regexp_replace(name, '\s+', '-', 'g'))
  WHERE slug IS NULL;

ALTER TABLE public.vehicle_makes ALTER COLUMN slug SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicle_makes_slug_key') THEN
    ALTER TABLE public.vehicle_makes ADD CONSTRAINT vehicle_makes_slug_key UNIQUE (slug);
  END IF;
END $$;

-- 2. Extend vehicle_models
ALTER TABLE public.vehicle_models
  ADD COLUMN IF NOT EXISTS slug       TEXT,
  ADD COLUMN IF NOT EXISTS status     TEXT NOT NULL DEFAULT 'approved'
                                           CHECK (status IN ('approved','pending','rejected')),
  ADD COLUMN IF NOT EXISTS created_by UUID REFERENCES auth.users(id) ON DELETE SET NULL;

UPDATE public.vehicle_models
  SET slug = lower(regexp_replace(name, '\s+', '-', 'g'))
  WHERE slug IS NULL;

ALTER TABLE public.vehicle_models ALTER COLUMN slug SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conname = 'vehicle_models_make_id_slug_key') THEN
    ALTER TABLE public.vehicle_models ADD CONSTRAINT vehicle_models_make_id_slug_key UNIQUE (make_id, slug);
  END IF;
END $$;

-- 3. Trigram indexes
CREATE INDEX IF NOT EXISTS vehicle_makes_name_trgm  ON public.vehicle_makes  USING gin (name gin_trgm_ops);
CREATE INDEX IF NOT EXISTS vehicle_models_name_trgm ON public.vehicle_models USING gin (name gin_trgm_ops);

-- 4. RLS
DROP POLICY IF EXISTS "vehicle_makes: public read"  ON public.vehicle_makes;
DROP POLICY IF EXISTS "vehicle_models: public read" ON public.vehicle_models;
DROP POLICY IF EXISTS "makes readable"              ON public.vehicle_makes;
DROP POLICY IF EXISTS "models readable"             ON public.vehicle_models;
DROP POLICY IF EXISTS "makes propose"               ON public.vehicle_makes;
DROP POLICY IF EXISTS "models propose"              ON public.vehicle_models;

CREATE POLICY "makes readable"  ON public.vehicle_makes  FOR SELECT USING (status = 'approved' OR created_by = auth.uid());
CREATE POLICY "models readable" ON public.vehicle_models FOR SELECT USING (status = 'approved' OR created_by = auth.uid());
CREATE POLICY "makes propose"   ON public.vehicle_makes  FOR INSERT TO authenticated WITH CHECK (status = 'pending' AND created_by = auth.uid());
CREATE POLICY "models propose"  ON public.vehicle_models FOR INSERT TO authenticated WITH CHECK (status = 'pending' AND created_by = auth.uid());

-- 5. Link public.vehicles to catalogue (preserve existing free-text columns)
ALTER TABLE public.vehicles
  ADD COLUMN IF NOT EXISTS make_id      UUID REFERENCES public.vehicle_makes(id),
  ADD COLUMN IF NOT EXISTS model_id     UUID REFERENCES public.vehicle_models(id),
  ADD COLUMN IF NOT EXISTS custom_make  TEXT,
  ADD COLUMN IF NOT EXISTS custom_model TEXT,
  ADD COLUMN IF NOT EXISTS is_custom    BOOLEAN NOT NULL DEFAULT false;

